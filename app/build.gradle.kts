// Release signing comes from environment variables set by CI from repo secrets
// (repo is public, so the keystore itself is never committed). Locally, these
// are simply unset and the release build falls back to the debug keystore so
// `./gradlew assembleRelease` still works for local experimentation.
val keystorePropertiesFile = rootProject.file("keystore.properties")
val keystoreProperties = Properties().apply {
    if (keystorePropertiesFile.exists()) {
        keystorePropertiesFile.inputStream().use { load(it) }
    }
}

fun signingProp(name: String): String? =
    System.getenv(name) ?: keystoreProperties.getProperty(name)

