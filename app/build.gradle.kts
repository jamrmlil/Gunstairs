            create("release") {
                storeFile = file(releaseKeystorePath!!)
                storePassword = signingProp("GUNSTAIRS_KEYSTORE_PASSWORD")
                keyAlias = signingProp("GUNSTAIRS_KEY_ALIAS")
                keyPassword = signingProp("GUNSTAIRS_KEY_PASSWORD")
            }
        }
